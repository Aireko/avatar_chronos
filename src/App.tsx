import { type FormEvent, useEffect, useState } from "react";
import { backendVersion, errorMessage, greet, identicon, type Identicon } from "./backend";
import "./App.css";

function App() {
  const [name, setName] = useState("");
  const [version, setVersion] = useState<string>();
  const [avatar, setAvatar] = useState<Identicon>();
  const [greeting, setGreeting] = useState("");
  const [error, setError] = useState("");

  useEffect(() => {
    backendVersion().then(setVersion, (e: unknown) => setError(errorMessage(e)));
  }, []);

  // Redraw the identicon whenever the name changes, ignoring replies for stale names.
  useEffect(() => {
    let current = true;
    identicon(name).then(
      (icon) => {
        if (current) setAvatar(icon);
      },
      (e: unknown) => {
        if (current) setError(errorMessage(e));
      },
    );
    return () => {
      current = false;
    };
  }, [name]);

  async function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    try {
      setGreeting(await greet(name));
      setError("");
    } catch (e) {
      setGreeting("");
      setError(errorMessage(e));
    }
  }

  return (
    <main className="container">
      <h1>Tauri + React + C</h1>
      <p className="subtitle">{version ? `C backend v${version}` : "C backend not connected"}</p>

      {avatar && <IdenticonView icon={avatar} />}

      <form className="row" onSubmit={onSubmit}>
        <input
          id="greet-input"
          value={name}
          onChange={(e) => {
            setName(e.currentTarget.value);
            setError("");
          }}
          placeholder="Enter a name..."
        />
        <button type="submit">Greet</button>
      </form>

      {greeting && <p>{greeting}</p>}
      {error && (
        <p className="error" role="alert">
          {error}
        </p>
      )}
    </main>
  );
}

function IdenticonView({ icon }: { icon: Identicon }) {
  const fill = `hsl(${icon.hue} 65% 50%)`;
  return (
    <svg
      className="identicon"
      viewBox={`-0.5 -0.5 ${icon.size + 1} ${icon.size + 1}`}
      shapeRendering="crispEdges"
      role="img"
      aria-label="Identicon generated by the C backend"
    >
      {icon.cells.map((filled, i) =>
        filled ? (
          <rect key={i} x={i % icon.size} y={Math.floor(i / icon.size)} width={1} height={1} fill={fill} />
        ) : null,
      )}
    </svg>
  );
}

export default App;
